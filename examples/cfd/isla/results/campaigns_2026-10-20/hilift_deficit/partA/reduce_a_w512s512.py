# HILIFT-090: reduce_a.py with "old" = r80_hl_isla_w512_s512 (the old reference of the notebook, 0.0407), not r80_hl_isla_ref.
"""HILIFT-090 Part A: per-case error analysis of A2 ISLA on HiLift (highlift_surface_medium, 180 val cases, 200k cells,
float32, epoch 500). Makes every number in RESULTS_A.md; writes percase.csv and tables_a.md.

Inputs (read-only):
  ../../isla-udrv-hl-2026-10-18/scores/<run>/<p>/<run>/metrics.jsonl   a2r_hl_isla, udrv_hl_gt, udrv_hl_t,
      r80_hl_gt_h256 (_s200k: LHR re-score of the CHAR GeoTransolver, for the subsample-noise estimate)
  examples/cfd/isla/results/campaigns_2026-10-02/char/protocols/<run>/<p>/metrics.jsonl  r80_hl_isla_ref (old ISLA),
      r80_hl_gt_h256 (CHAR record, other 200k subsample)
  hl_medium_manifest.json  (LHR .../highlift/manifests; train 510 / val 180; == medium_train/medium_val of splits)
  splits_manifest.json     (LHR dataset root manifest.json: stall_test = post-stall cases, deflection_test = the
      36 geometries with the highest mean flap/slat deflection)
  case_meta.json           (LHR <case>/<case>_element_labels.json: n_cells, total area, element area shares; val only)
Conventions as udrv_table.py: last infer_step row per sample id, prefix "NNNNN_" stripped, then "_domain_..." dropped.
usage: nice -n 19 python3 reduce_a.py
"""
import csv, json, os, re
import numpy as np
from scipy.stats import spearmanr

H = os.path.dirname(os.path.abspath(__file__))
U = f"{H}/../../isla-udrv-hl-2026-10-18/scores"
CH = f"{H}/../../../examples/cfd/isla/results/campaigns_2026-10-02/char/protocols"
P = ("native", "area", "posed"); S = ("42", "43"); FL = {"p": "pressure_l2", "wss": "tau_wall_l2"}
ARMS = {  # key -> path(seed, protocol)
    "isla": lambda s, p: f"{U}/a2r_hl_isla_seed{s}/{p}/a2r_hl_isla_seed{s}/metrics.jsonl",
    "gt": lambda s, p: f"{U}/udrv_hl_gt_seed{s}/{p}/udrv_hl_gt_seed{s}/metrics.jsonl",
    "t": lambda s, p: f"{U}/udrv_hl_t_seed{s}/{p}/udrv_hl_t_seed{s}/metrics.jsonl",
    "old": lambda s, p: f"{CH}/r80_hl_isla_w512_s512_seed{s}/{p}/metrics.jsonl",
    "gtphys_char": lambda s, p: f"{CH}/r80_hl_gt_h256_seed{s}/{p}/metrics.jsonl",
    "gtphys_lhr": lambda s, p: f"{U}/r80_hl_gt_h256_seed{s}_s200k/{p}/r80_hl_gt_h256_seed{s}/metrics.jsonl",
}
OUT = []


def out(s=""):
    OUT.append(s); print(s)


def load(fp):
    by = {}
    for line in open(fp):
        r = json.loads(line)
        if r.get("phase") == "infer_step":
            by[re.sub(r"_domain_.*$", "", re.sub(r"^\d+_", "", r["sample_id"]))] = r["metrics"]
    return by


man = json.load(open(f"{H}/hl_medium_manifest.json")); spl = json.load(open(f"{H}/splits_manifest.json"))
meta = json.load(open(f"{H}/case_meta.json"))
VAL = sorted(man["val"]); TR = man["train"]
geo = lambda c: c.split("_")[1]; aoa = lambda c: int(c.split("_")[-1])
POST = set(spl["stall_test"]); HIDEF = {geo(c) for c in spl["deflection_test"]}
# E[arm][prot][seed][field] -> np.array over VAL
E = {a: {p: {s: {} for s in S} for p in P} for a in ARMS}
for a, f in ARMS.items():
    for p in P:
        for s in S:
            by = load(f(s, p)); assert set(by) == set(VAL), (a, p, s, len(set(by) & set(VAL)))
            for k, m in FL.items():
                E[a][p][s][k] = np.array([by[c][m] for c in VAL])
M = lambda a, k, p="native": (E[a][p]["42"][k] + E[a][p]["43"][k]) / 2  # seed mean per case
A = np.array([aoa(c) for c in VAL]); G = [geo(c) for c in VAL]
AOAS = sorted(set(A))

out("# HILIFT-090 Part A tables (generated by reduce_a.py)\n")
# ---------- overall ----------
out("## 0. Overall case-mean errors (native, seed mean) and subsample noise\n")
out("| arm | p | wss |\n|---|---|---|")
for a in ARMS:
    out(f"| {a} | {M(a,'p').mean():.4f} | {M(a,'wss').mean():.4f} |")
for k in FL:
    for s in S:
        r = E["gtphys_char"]["native"][s][k] / E["gtphys_lhr"]["native"][s][k]
        out(f"\nsubsample noise, GT phys CHAR/LHR re-score, {k} seed{s}: mean-ratio {E['gtphys_char']['native'][s][k].mean()/E['gtphys_lhr']['native'][s][k].mean():.4f}, "
            f"per-case ratio median {np.median(r):.4f}, sd {np.std(r):.4f}, |r-1| p90 {np.quantile(abs(r-1),.9):.4f}, max {abs(r-1).max():.4f}")
    r = M("gtphys_char", k) / M("gtphys_lhr", k)
    out(f"seed-mean {k}: per-case ratio sd {np.std(r):.4f}, |r-1| p90 {np.quantile(abs(r-1),.9):.4f}, corr(log r, AoA) spearman {spearmanr(r, A)[0]:.3f}")

# ---------- Q2 training distribution ----------
out("\n## Q2. Training / validation distribution\n")
out("| AoA | train cases | val cases | train geometries |\n|---|---|---|---|")
for v in AOAS:
    tr = [c for c in TR if aoa(c) == v]
    out(f"| {v} | {len(tr)} | {sum(A==v)} | {len({geo(c) for c in tr})} |")
trg = {}
for c in TR: trg.setdefault(geo(c), []).append(aoa(c))
valg = {}
for c in VAL: valg.setdefault(geo(c), []).append(aoa(c))
allg = sorted(set(trg) | set(valg))
out(f"\ngeometries: train {len(trg)}, val {len(valg)}, union {len(allg)}, val geometries absent from train: {len(set(valg)-set(trg))}")
out(f"train cases per geometry: min {min(map(len,trg.values()))}, median {np.median([len(v) for v in trg.values()])}, max {max(map(len,trg.values()))}")
out(f"val cases per geometry: distribution {dict(sorted({n: sum(len(v)==n for v in valg.values()) for n in set(map(len,valg.values()))}.items()))}")
hi_tr = [c for c in TR if aoa(c) >= 16]
out(f"train cases with AoA>=16: {len(hi_tr)} of {len(TR)} ({len(hi_tr)/len(TR):.1%}); geometries with >=1 AoA>=16 train case: {len({geo(c) for c in hi_tr})} of {len(trg)}")
out(f"val cases with AoA>=16: {sum(A>=16)} of 180; post-stall (stall_test) val cases: {sum(c in POST for c in VAL)}; post-stall train cases: {sum(c in POST for c in TR)}")
out(f"post-stall share by AoA (val): " + ", ".join(f"{v}:{sum((A==v)&np.array([c in POST for c in VAL]))}/{sum(A==v)}" for v in AOAS))

# ---------- Q1 by AoA ----------
def by_aoa(vals, ref_pairs, title):
    out(f"\n### {title}\n")
    hdr = "| AoA | n | " + " | ".join(f"{n} mean | {n} med" for n in vals) + " | " + " | ".join(f"share of gap {lab}" for lab, *_ in ref_pairs) + " |"
    out(hdr); out("|" + "---|" * (2 + 2 * len(vals) + len(ref_pairs)))
    for v in AOAS + ["all"]:
        m = np.ones_like(A, bool) if v == "all" else A == v
        row = f"| {v} | {m.sum()} | " + " | ".join(f"{x[m].mean():.4f} | {np.median(x[m]):.4f}" for x in vals.values())
        row += " | " + " | ".join(f"{(a[m]-b[m]).sum()/(a-b).sum():.1%}" for _, a, b in ref_pairs) + " |"
        out(row)
    for lab, a, b in ref_pairs:
        out(f"\n{lab}: total gap {((a-b).mean()):.4f} (ratio of means {a.mean()/b.mean():.4f}); AoA>=16 share {(a-b)[A>=16].sum()/(a-b).sum():.1%} "
            f"with {np.mean(A>=16):.0%} of cases; per-case ratio median {np.median(a/b):.3f}; cases where {lab.split()[0]} worse: {np.mean(a>b):.0%}; "
            f"spearman(ratio, AoA) {spearmanr(a/b, A)[0]:.3f}")


out("\n## Q1. Error vs AoA (native, seed means)")
for k in FL:
    I, Gt, T = M("isla", k), M("gt", k), M("t", k)
    by_aoa({"ISLA": I, "GT": Gt, "T": T}, [("ISLA-GT", I, Gt), ("ISLA-T", I, T)], f"{k}")
    out("\nper-AoA ratio of means ISLA/GT, ISLA/T: " + ", ".join(f"{v}: {I[A==v].mean()/Gt[A==v].mean():.3f}/{I[A==v].mean()/T[A==v].mean():.3f}" for v in AOAS))

# ---------- Q1 by geometry / what separates bad from ok at high AoA ----------
out("\n## Q1b. Geometry and high-AoA structure (pressure unless noted)\n")
post = np.array([c in POST for c in VAL]); hidef = np.array([g in HIDEF for g in G])
I, Gt, T = M("isla", "p"), M("gt", "p"), M("t", "p")
hi = A >= 16
out("No per-geometry flap/slat deflection table exists in the dataset root, the manifest, or examples/cfd/{isla,external_aerodynamics};"
    " proxies used: deflection_test membership (36 highest-mean-deflection geometries), stall_test membership (post-stall case), element area shares.")
for lab, mask in [("post-stall", post), ("pre-stall", ~post), ("hi-deflection geo", hidef), ("other geo", ~hidef)]:
    for hl, hm in [("AoA>=16", hi), ("AoA<=14", ~hi)]:
        m = mask & hm
        if m.sum():
            out(f"- {lab} & {hl}: n={m.sum()}, ISLA {I[m].mean():.4f}, GT {Gt[m].mean():.4f}, T {T[m].mean():.4f}, ISLA/GT {I[m].mean()/Gt[m].mean():.3f}, "
                f"share of ISLA-GT gap {(I[m]-Gt[m]).sum()/(I-Gt).sum():.1%}")
# concentration: top cases share of gap
d = I - Gt; o = np.argsort(-d)
for n in (5, 10, 18, 36):
    out(f"- top {n} cases by ISLA-GT pressure gap carry {d[o[:n]].sum()/d.sum():.1%} of the total gap; their AoA: {sorted(A[o[:n]].tolist()) if n<=18 else np.bincount(A[o[:n]]).nonzero()[0].tolist()}")
out(f"- top 10 gap cases: " + "; ".join(f"{VAL[i]} (ISLA {I[i]:.3f}, GT {Gt[i]:.3f}, post-stall {post[i]}, hidef {hidef[i]})" for i in o[:10]))
out("\ntop 10 ISLA-GT pressure-gap cases, per seed (s42/s43) and the same-geometry train AoAs:\n")
out("| case | ISLA | old ISLA | GT | T | GT phys (LHR) | share of ISLA-GT gap | train AoAs same geo |\n|---|---|---|---|---|---|---|---|")
for i in o[:10]:
    f2 = lambda a: f"{E[a]['native']['42']['p'][i]:.3f}/{E[a]['native']['43']['p'][i]:.3f}"
    out(f"| {VAL[i]} | {f2('isla')} | {f2('old')} | {f2('gt')} | {f2('t')} | {f2('gtphys_lhr')} | {d[i]/d.sum():.1%} | {sorted(trg.get(G[i], []))} |")
for kk in (0, 1, 3, 5, 10):
    keep = np.ones(len(VAL), bool); keep[o[:kk]] = False
    for k2 in FL:
        a_, b_, c_ = M("isla", k2)[keep], M("gt", k2)[keep], M("t", k2)[keep]
        out(f"- drop top {kk} ISLA-GT p-gap cases: {k2} ISLA/GT {a_.mean()/b_.mean():.4f}, ISLA/T {a_.mean()/c_.mean():.4f}")
# bistable cases: some run (5 arms x 2 seeds) is > 2x the best run on that case
RUNS = [(a, s) for a in ("isla", "old", "gt", "t", "gtphys_lhr") for s in S]
X = np.array([E[a]["native"][s]["p"] for a, s in RUNS])  # runs x cases
bist = (X.max(0) > 0.08) & (X.max(0) > 2 * X.min(0))
out(f"\nbranch cases (max over 10 runs > 0.08 and > 2x min): {bist.sum()}, AoA {sorted(A[bist].tolist())}; they carry {d[bist].sum()/d.sum():.1%} of the ISLA-GT p gap, "
    f"{(I-T)[bist].sum()/(I-T).sum():.1%} of ISLA-T; without them ISLA/GT {I[~bist].mean()/Gt[~bist].mean():.4f}, ISLA/T {I[~bist].mean()/T[~bist].mean():.4f}, "
    f"A2/old {I[~bist].mean()/M('old','p')[~bist].mean():.4f}")
for k2 in FL:
    for s in S:
        out(f"- per-seed ratio of means {k2} seed{s}: ISLA/GT {E['isla']['native'][s][k2].mean()/E['gt']['native'][s][k2].mean():.4f}, ISLA/T {E['isla']['native'][s][k2].mean()/E['t']['native'][s][k2].mean():.4f}")
# is it few geometries? per-geometry gap at AoA>=16
gh = {}
for i in np.nonzero(hi)[0]: gh.setdefault(G[i], []).append(d[i])
gs = sorted(gh.items(), key=lambda x: -sum(x[1]))
tot = d[hi].sum()
out(f"- AoA>=16 val cases come from {len(gh)} geometries ({hi.sum()} cases); top 5 geometries carry {sum(sum(v) for _,v in gs[:5])/tot:.1%} of the AoA>=16 gap, top 10 {sum(sum(v) for _,v in gs[:10])/tot:.1%}; "
    f"ISLA worse than GT in {np.mean(d[hi]>0):.0%} of AoA>=16 cases (gap>0.02 abs in {np.mean(d[hi]>0.02):.0%})")
# Within high AoA: correlates of ISLA error and of ISLA-GT gap
def nearest_train(c):
    a = [x for x in trg.get(geo(c), [])]; return min(abs(x - aoa(c)) for x in a) if a else 99
feat = {
    "AoA": A.astype(float), "post_stall": post.astype(float), "hi_deflection": hidef.astype(float),
    "GT error (difficulty)": Gt, "T error": T,
    "n train cases same geo": np.array([len(trg.get(g, [])) for g in G], float),
    "n train AoA>=16 same geo": np.array([sum(x >= 16 for x in trg.get(g, [])) for g in G], float),
    "|dAoA| to nearest same-geo train case": np.array([nearest_train(c) for c in VAL], float),
    "slat area share": np.array([meta.get(c, {}).get("share", {}).get("slat", np.nan) for c in VAL]),
    "flap area share": np.array([meta.get(c, {}).get("share", {}).get("flap", np.nan) for c in VAL]),
    "n_cells": np.array([meta.get(c, {}).get("n_cells", np.nan) for c in VAL], float),
}
out(f"\nSpearman correlations within AoA>=16 (n={hi.sum()}) [and all 180] with ISLA p error, ISLA/GT p ratio, ISLA-GT p gap:\n")
out("| feature | rho(ISLA err) hi | rho(ISLA/GT) hi | rho(ISLA-GT) hi | rho(ISLA err) all | rho(ISLA/GT) all |\n|---|---|---|---|---|---|")
for n, x in feat.items():
    ok = ~np.isnan(x); h = ok & hi
    out(f"| {n} | {spearmanr(x[h], I[h])[0]:.2f} | {spearmanr(x[h], (I/Gt)[h])[0]:.2f} | {spearmanr(x[h], d[h])[0]:.2f} | {spearmanr(x[ok], I[ok])[0]:.2f} | {spearmanr(x[ok], (I/Gt)[ok])[0]:.2f} |")
# bad vs ok within hi-AoA: split by ISLA/GT ratio median
r = I / Gt; med = np.median(r[hi]); bad = hi & (r > med); okm = hi & (r <= med)
out(f"\nwithin AoA>=16, split at median ISLA/GT={med:.3f}: bad n={bad.sum()} vs ok n={okm.sum()}")
for n, x in feat.items():
    out(f"- {n}: bad {np.nanmean(x[bad]):.4g} vs ok {np.nanmean(x[okm]):.4g}")

# ---------- Q3 A2 vs old ----------
out("\n## Q3. A2 ISLA vs old reference ISLA (CHAR r80_hl_isla_w512_s512, the 512-wide 512-slice reference the notebook compares; different 200k subsample)\n")
for k in FL:
    for s in ("42", "43", "mean"):
        a = M("isla", k) if s == "mean" else E["isla"]["native"][s][k]
        b = M("old", k) if s == "mean" else E["old"]["native"][s][k]
        rr = a / b
        out(f"\n### {k}, seed {s}: A2/old ratio of means {a.mean()/b.mean():.4f}; per-case ratio median {np.median(rr):.4f}; A2 worse in {np.mean(rr>1):.0%} (>1.03 in {np.mean(rr>1.03):.0%}, <0.97 in {np.mean(rr<0.97):.0%}); spearman(ratio, AoA) {spearmanr(rr, A)[0]:.3f}; spearman(ratio, old err) {spearmanr(rr, b)[0]:.3f}\n")
        out("| AoA | n | A2 mean | old mean | ratio of means | median per-case ratio | share of A2-old gap |\n|---|---|---|---|---|---|---|")
        for v in AOAS:
            m = A == v
            out(f"| {v} | {m.sum()} | {a[m].mean():.4f} | {b[m].mean():.4f} | {a[m].mean()/b[m].mean():.3f} | {np.median(rr[m]):.3f} | {(a[m]-b[m]).sum()/(a-b).sum():.1%} |")
        dd = a - b; oo = np.argsort(-dd)
        out(f"\ntop 10 cases carry {dd[oo[:10]].sum()/dd.sum():.1%} of the gap (AoA {sorted(A[oo[:10]].tolist())}); top 18: {dd[oo[:18]].sum()/dd.sum():.1%}; AoA>=16 share {dd[hi].sum()/dd.sum():.1%}")
# reference: same-arm GT CHAR vs LHR per AoA, to show the subsample noise per bin
out("\nNoise reference, GT phys CHAR/LHR (same model, two subsamples) ratio of means by AoA, seed mean, p / wss: " +
    ", ".join(f"{v}: {M('gtphys_char','p')[A==v].mean()/M('gtphys_lhr','p')[A==v].mean():.3f}/{M('gtphys_char','wss')[A==v].mean()/M('gtphys_lhr','wss')[A==v].mean():.3f}" for v in AOAS))

# ---------- Q4 seed consistency ----------
out("\n## Q4. Seed consistency (native)\n")
out("| arm | field | spearman s42 vs s43 | top-18 overlap | top-36 overlap | worst-5 s42 | worst-5 s43 |\n|---|---|---|---|---|---|---|")
for a in ARMS:
    for k in FL:
        x, y = E[a]["native"]["42"][k], E[a]["native"]["43"][k]
        t = lambda z, n: set(np.argsort(-z)[:n])
        w = lambda z: ",".join(VAL[i].replace("geo_", "").replace("_AoA", "") for i in np.argsort(-z)[:5])
        out(f"| {a} | {k} | {spearmanr(x,y)[0]:.3f} | {len(t(x,18)&t(y,18))}/18 | {len(t(x,36)&t(y,36))}/36 | {w(x)} | {w(y)} |")
for k in FL:
    for s in S:
        x = E["isla"]["native"][s][k] - E["gt"]["native"][s][k]
        y = E["isla"]["native"]["43" if s == "42" else "42"][k] - E["gt"]["native"]["43" if s == "42" else "42"][k]
    out(f"ISLA-GT {k} gap, s42 vs s43 (each arm's own seed): spearman {spearmanr(E['isla']['native']['42'][k]-E['gt']['native']['42'][k], E['isla']['native']['43'][k]-E['gt']['native']['43'][k])[0]:.3f}; "
        f"A2-old: spearman {spearmanr(E['isla']['native']['42'][k]-E['old']['native']['42'][k], E['isla']['native']['43'][k]-E['old']['native']['43'][k])[0]:.3f}")
x, y = M("isla", "p"), M("gt", "p")
out(f"cross-model rank agreement (seed means, p): ISLA vs GT {spearmanr(x,y)[0]:.3f}, ISLA vs T {spearmanr(x,M('t','p'))[0]:.3f}, GT vs T {spearmanr(y,M('t','p'))[0]:.3f}, ISLA vs old {spearmanr(x,M('old','p'))[0]:.3f}")

# ---------- Q5 protocol ratios ----------
out("\n## Q5. A2 ISLA protocol ratios per case\n")
ncell = feat["n_cells"]
for p in ("posed", "area"):
    for k in FL:
        for s in S + ("mean",):
            a = M("isla", k, p) if s == "mean" else E["isla"][p][s][k]
            b = M("isla", k) if s == "mean" else E["isla"]["native"][s][k]
            rr = a / b; ok = ~np.isnan(ncell)
            out(f"- {p}/native {k} seed {s}: ratio of means {a.mean()/b.mean():.4f}; per-case median {np.median(rr):.4f}, sd {np.std(rr):.4f}, min {rr.min():.3f}, max {rr.max():.3f}; "
                f"spearman vs AoA {spearmanr(rr,A)[0]:.2f}, vs n_cells {spearmanr(rr[ok],ncell[ok])[0]:.2f}, vs native err {spearmanr(rr,b)[0]:.2f}; "
                f"share of the mean shift from AoA>=16 {(a-b)[hi].sum()/(a-b).sum():.0%}")
        a, b = M("isla", k, p), M("isla", k)
        out(f"  by AoA ({k}, seed mean, ratio of means): " + ", ".join(f"{v}: {a[A==v].mean()/b[A==v].mean():.4f}" for v in AOAS))
        out(f"  by AoA ({k}, seed mean, mean absolute shift {p} - native, x1e-4): " + ", ".join(f"{v}: {1e4*(a[A==v]-b[A==v]).mean():.1f}" for v in AOAS)
            + f"; overall {1e4*(a-b).mean():.1f}, spearman(abs shift, native err) {spearmanr(a-b, b)[0]:.2f}")
    for ar in ("gt", "t", "old"):
        out(f"  reference {ar} {p}/native p: {M(ar,'p',p).mean()/M(ar,'p').mean():.4f}, wss: {M(ar,'wss',p).mean()/M(ar,'wss').mean():.4f}")

# ---------- percase.csv ----------
with open(f"{H}/percase_w512s512.csv", "w", newline="") as fh:
    w = csv.writer(fh)
    cols = ["case", "geometry", "aoa", "post_stall", "hi_deflection_geo", "n_train_same_geo", "n_cells"]
    for a in ("isla", "gt", "t", "old", "gtphys_char", "gtphys_lhr"):
        cols += [f"{a}_p", f"{a}_wss"]
    cols += ["isla_posed_over_native_p", "isla_posed_over_native_wss", "isla_area_over_native_p", "isla_area_over_native_wss"]
    w.writerow(cols)
    for i, c in enumerate(VAL):
        row = [c, G[i], A[i], int(post[i]), int(hidef[i]), len(trg.get(G[i], [])), meta.get(c, {}).get("n_cells", "")]
        for a in ("isla", "gt", "t", "old", "gtphys_char", "gtphys_lhr"):
            row += [f"{M(a,'p')[i]:.6f}", f"{M(a,'wss')[i]:.6f}"]
        for p in ("posed", "area"):
            for k in FL:
                row.append(f"{M('isla',k,p)[i]/M('isla',k)[i]:.6f}")
        w.writerow(row)
open(f"{H}/tables_a_w512s512.md", "w").write("\n".join(OUT) + "\n")
